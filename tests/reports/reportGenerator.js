async function saveReports(results) {
    const reportsDir = path.join(__dirname, "..", "reports");
    if (!fs.existsSync(reportsDir)) {
        fs.mkdirSync(reportsDir, { recursive: true });
    }

    const mdContent = generateMarkdownReport(results);
    const htmlContent = generateHtmlReport(results);

    // Save in tests/reports/
    fs.writeFileSync(path.join(reportsDir, "qa-report.md"), mdContent, "utf-8");
    fs.writeFileSync(path.join(reportsDir, "qa-report.html"), htmlContent, "utf-8");

    // Also copy to root directory for convenient access
    const rootDir = path.join(__dirname, "..", "..");
    fs.writeFileSync(path.join(rootDir, "qa-report.md"), mdContent, "utf-8");
    fs.writeFileSync(path.join(rootDir, "qa-report.html"), htmlContent, "utf-8");

    console.log(`[QA Report] Generated successfully:`);
    console.log(`  - ${path.join(rootDir, "qa-report.html")}`);
    console.log(`  - ${path.join(rootDir, "qa-report.md")}`);

    return { mdPath: path.join(rootDir, "qa-report.md"), htmlPath: path.join(rootDir, "qa-report.html") };
}

module.exports = {
    generateMarkdownReport,
    generateHtmlReport,
    saveReports
};
